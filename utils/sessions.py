"""Who is signed in, and the way to take that away.

A Flask session is a signed cookie: the server can tell that it wrote it, and
cannot tell later that it wants it back. So every property this project needed
from a sign-in ended up being a property of the *token* rather than of the
session — the cookie expires in eight hours, and "sign me out everywhere" was
something the operator could only achieve by changing ``FLASK_SECRET_KEY`` and
restarting the host, which signs out the browser they are using it on.

This module is the missing half: a row per signed-in session, a ``sid`` in the
cookie, and a revocation that takes effect on the next request. It is what makes
three questions answerable, all of them the operator's:

* **Who is signed in right now?** Which scope, which server, which Discord
  account, from which address, since when, and when it was last used.
* **Get that one out.** A session on a machine somebody no longer trusts can be
  closed without touching anybody else's.
* **Get them all out.** Every row aside from this one, in a single call.

Three rules that are deliberate, and are the ones a reader should check rather
than trust:

1. **A session with no ``sid`` is respected, and adopted on its first request.**
   Without that, deploying this change would sign out every open console — and a
   session minted by a build that cannot write to the database (read-only disk,
   a restore that raced this table) would be unusable rather than merely
   unrevocable. Adoption is attempted once per request and gives up quietly: if
   the write fails, no ``sid`` is stored, the session keeps working, and the
   console says the ledger could not be written. It is signed in either way.
2. **An ``sid`` the ledger does not know is refused.** The reverse of the above,
   and the reason both are here: once a session *has* a row, the row is the
   authority. A sid with no row means the database was replaced by an older
   backup, or wiped — and the honest answer to "is this session still valid" is
   not known, which is the one case that must not be answered "yes". The cost is
   real and small: a restore signs devices out and they sign in again.
3. **Revocation is checked on every request, through a five-second cache.** Not
   an in-memory session object: the sid is verified against the row, so a
   revocation lands on the next request rather than at the browser's next
   reload. The cache exists because ``is_authenticated`` runs several times per
   request and this table lives in SQLite; five seconds is short enough that the
   operator's own click is the thing that closes the door.

Nothing in here reads a value out of a cookie, a query string or a header: the
sid is generated by :func:`start`, and the only other thing that ever hands one
in is Flask's own signed session.
"""
from __future__ import annotations

import secrets
import sqlite3
import threading
import time

from utils import db

#: Where the sid lives in Flask's session, and therefore in the cookie.
COOKIE_KEY = "sid"

#: How long a session may go *unused* before the row expires. Matches
#: ``PERMANENT_SESSION_LIFETIME`` in ``keep_alive`` — the cookie and the row
#: should disagree about a session for as short a time as possible.
IDLE_TTL_SECONDS = 8 * 3600

#: How long a revoked row is kept as a record before being pruned.
REVOKED_KEEP_SECONDS = 7 * 24 * 3600

#: How long a live check may be believed without re-reading the row.
CHECK_CACHE_SECONDS = 5.0

#: How long the ledger stays quiet about a failed write. One attempt per request
#: would be a write storm on a read-only database, and the failure is a fact
#: about the host — repeating it 200 times a second does not learn anything new.
WRITE_BACKOFF_SECONDS = 60.0

TABLE = """CREATE TABLE IF NOT EXISTS dashboard_sessions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    sid TEXT NOT NULL UNIQUE,
    scope TEXT NOT NULL DEFAULT '',
    guild_id INTEGER,
    user_id INTEGER,
    label TEXT NOT NULL DEFAULT '',
    ip TEXT NOT NULL DEFAULT '',
    agent TEXT NOT NULL DEFAULT '',
    started_at REAL NOT NULL DEFAULT 0,
    seen_at REAL NOT NULL DEFAULT 0,
    expires_at REAL NOT NULL DEFAULT 0,
    revoked_at REAL
)"""

INDEX = (
    "CREATE INDEX IF NOT EXISTS idx_sessions_live "
    "ON dashboard_sessions(revoked_at, expires_at)"
)

_ensure_lock = threading.Lock()
_ensured = False
_cache_lock = threading.Lock()
_cache: dict[str, tuple[float, bool]] = {}
_last_seen_write: dict[str, float] = {}
_write_failed_at = 0.0


# --------------------------------------------------------------------------- #
# Talking to the table
# --------------------------------------------------------------------------- #
def _connect() -> sqlite3.Connection:
    conn = db.connect()
    conn.row_factory = sqlite3.Row
    return conn


def _ensure(conn: sqlite3.Connection) -> None:
    """Create the table once per process, if it is not already there.

    Declared in ``utils/db.setup`` as well, following the convention every other
    table here follows: a database restored from a backup taken before this
    feature existed has to be able to start with an empty ledger rather than
    failing every sign-in.
    """
    global _ensured
    if _ensured:
        return
    with _ensure_lock:
        if _ensured:
            return
        conn.execute(TABLE)
        conn.execute(INDEX)
        conn.commit()
        _ensured = True


def _run(work):
    """Run ``work(conn)`` against the ledger, or answer ``None``.

    Every failure is contained here on purpose: a dashboard that cannot read its
    own ledger must keep serving pages. Callers distinguish "no row" from "could
    not read" by the sentinel they ask for, not by an exception.
    """
    global _ensured
    try:
        conn = _connect()
    except sqlite3.Error:
        return None
    try:
        try:
            _ensure(conn)
        except sqlite3.Error:
            pass
        return work(conn)
    except sqlite3.OperationalError:
        # The table was there a moment ago and is not now: the file was replaced
        # (a restore, a wipe) under this process. Recreate and try once more.
        _ensured = False
        try:
            _ensure(conn)
            return work(conn)
        except sqlite3.Error:
            return None
    except sqlite3.Error:
        return None
    finally:
        conn.close()


def _writes_allowed() -> bool:
    """Whether a write is worth attempting right now (see the backoff above)."""
    return (time.time() - _write_failed_at) > WRITE_BACKOFF_SECONDS


def _note_write_failure() -> None:
    global _write_failed_at
    _write_failed_at = time.time()


def _forget_cache(sid: str | None = None) -> None:
    with _cache_lock:
        if sid:
            _cache.pop(sid, None)
        else:
            _cache.clear()


def _mask(sid: str) -> str:
    """A session id as a page may show it: enough to match a row to a device."""
    if len(sid) <= 10:
        return sid
    return f"{sid[:6]}…{sid[-4:]}"


def _agent_label(agent: str) -> str:
    """A browser or tool as a person would name it, out of a User-Agent string.

    Deliberately crude and deliberately bounded: the console shows this beside an
    address so two of the operator's own sessions can be told apart, and a
    User-Agent is attacker-controlled text that must never be rendered as
    anything but a short, single-line label. Unrecognised values are kept, capped
    and stripped of control characters, because "curl" and "Googlebot" are
    exactly the labels worth seeing.
    """
    text = "".join(char for char in str(agent or "") if 32 <= ord(char) < 127)
    text = text.strip()[:200]
    for marker, name in (
        ("Edg/", "Edge"),
        ("OPR/", "Opera"),
        ("Chrome/", "Chrome"),
        ("Safari/", "Safari"),
        ("Firefox/", "Firefox"),
        ("curl/", "curl"),
        ("python-requests", "python-requests"),
    ):
        if marker in text:
            return name
    return text.split(" ")[0][:40] if text else "unknown"


# --------------------------------------------------------------------------- #
# Starting, checking, ending
# --------------------------------------------------------------------------- #
def start(
    scope: str,
    *,
    guild_id=None,
    user_id=None,
    label: str = "",
    ip: str = "",
    agent: str = "",
) -> str:
    """Record a new signed-in session and return its id, or ``""`` on failure.

    An empty return is not an error the caller has to handle: no sid stored means
    the session works and simply cannot be revoked, which is exactly what the
    console reports.
    """
    sid = secrets.token_urlsafe(32)
    now = time.time()
    row = (
        sid,
        str(scope or ""),
        int(guild_id) if guild_id else None,
        int(user_id) if user_id else None,
        str(label or "")[:120],
        str(ip or "")[:64],
        _agent_label(agent),
        now,
        now,
        now + IDLE_TTL_SECONDS,
    )

    def work(conn):
        conn.execute(
            "INSERT INTO dashboard_sessions "
            "(sid, scope, guild_id, user_id, label, ip, agent, started_at, seen_at, expires_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            row,
        )
        conn.commit()
        return True

    if not _writes_allowed():
        return ""
    if _run(work):
        _forget_cache(sid)
        return sid
    _note_write_failure()
    return ""


def live(sid: str | None) -> bool:
    """Whether the session behind ``sid`` may still be used.

    ``None``/``""`` is a session from before this ledger existed, or one this
    host could not record: respected (see the module docstring). A sid the
    ledger does not know is refused.
    """
    if not sid:
        return True
    now = time.time()
    with _cache_lock:
        cached = _cache.get(sid)
        if cached and now - cached[0] < CHECK_CACHE_SECONDS:
            return cached[1]

    row = _run(
        lambda conn: conn.execute(
            "SELECT seen_at, expires_at, revoked_at FROM dashboard_sessions WHERE sid = ?",
            (sid,),
        ).fetchone()
    )
    if row is None:
        # Two different situations, and they are answered differently: ``_run``
        # answers ``None`` for both "no such row" and "could not read". Ask the
        # second question directly, because getting it wrong one way signs out
        # every browser on a host whose disk hiccuped, and the other way lets a
        # revoked session through for as long as the failure lasts.
        readable = _run(lambda conn: conn.execute("SELECT 1").fetchone()) is not None
        if not readable:
            return True
        allowed = False
    else:
        allowed = row["revoked_at"] is None and (row["expires_at"] or 0) > now
        if allowed:
            _touch(sid, row, now)

    with _cache_lock:
        _cache[sid] = (now, allowed)
    return allowed


def _touch(sid: str, row, now: float) -> None:
    """Slide the idle deadline, at most once a minute per session."""
    last = _last_seen_write.get(sid, 0.0)
    if now - last < 60:
        return
    if not _writes_allowed():
        return
    _last_seen_write[sid] = now

    def work(conn):
        conn.execute(
            "UPDATE dashboard_sessions SET seen_at = ?, expires_at = ? WHERE sid = ?",
            (now, now + IDLE_TTL_SECONDS, sid),
        )
        conn.commit()
        return True

    if not _run(work):
        _note_write_failure()


def revoke(sid: str | None) -> bool:
    """End one session by its id. ``True`` when a live row was closed."""
    if not sid:
        return False
    now = time.time()

    def work(conn):
        cursor = conn.execute(
            "UPDATE dashboard_sessions SET revoked_at = ? "
            "WHERE sid = ? AND revoked_at IS NULL",
            (now, sid),
        )
        conn.commit()
        return cursor.rowcount > 0

    result = _run(work)
    _forget_cache(sid)
    return bool(result)


def revoke_row(row_id: int, *, keep: str | None = None) -> bool:
    """End one session by its row id, as the console names it."""
    now = time.time()

    def work(conn):
        cursor = conn.execute(
            "UPDATE dashboard_sessions SET revoked_at = ? "
            "WHERE id = ? AND revoked_at IS NULL AND (? IS NULL OR sid <> ?)",
            (now, int(row_id), keep, keep),
        )
        conn.commit()
        return cursor.rowcount > 0

    result = _run(work)
    _forget_cache()
    return bool(result)


def revoke_all(*, keep: str | None = None) -> int:
    """End every live session except ``keep`` (normally the caller's own)."""
    now = time.time()

    def work(conn):
        cursor = conn.execute(
            "UPDATE dashboard_sessions SET revoked_at = ? "
            "WHERE revoked_at IS NULL AND (? IS NULL OR sid <> ?)",
            (now, keep, keep),
        )
        conn.commit()
        return cursor.rowcount

    result = _run(work)
    _forget_cache()
    return int(result or 0)


def _prune(conn) -> None:
    cutoff = time.time() - REVOKED_KEEP_SECONDS
    conn.execute(
        "DELETE FROM dashboard_sessions "
        "WHERE revoked_at IS NOT NULL AND revoked_at < ?",
        (cutoff,),
    )
    conn.commit()


# --------------------------------------------------------------------------- #
# The reading
# --------------------------------------------------------------------------- #
def reading(*, current_sid: str | None = None) -> dict:
    """Every session the ledger knows, for the console's Access page.

    Says whether it could be read at all, because "no sessions" and "could not
    look" are different answers and a page that showed the first when it meant
    the second would be lying about the one thing this exists to show. The sid
    itself is masked — it is a bearer credential, and the page's job is to name
    a row to revoke rather than to hand out a session.
    """
    now = time.time()

    def work(conn):
        _prune(conn)
        rows = conn.execute(
            "SELECT id, sid, scope, guild_id, user_id, label, ip, agent, "
            "started_at, seen_at, expires_at, revoked_at "
            "FROM dashboard_sessions ORDER BY seen_at DESC LIMIT 200"
        ).fetchall()
        return [dict(row) for row in rows]

    rows = _run(work)
    if rows is None:
        return {
            "available": False,
            "because": (
                "The database could not be read, so this list is not a claim "
                "that nobody is signed in — it is a claim that nobody can say."
            ),
            "idle_ttl_seconds": IDLE_TTL_SECONDS,
            "rows": [],
            "live": 0,
            "revoked": 0,
        }

    listed = []
    live_count = 0
    revoked_count = 0
    for row in rows:
        revoked = row["revoked_at"] is not None
        expired = not revoked and (row["expires_at"] or 0) <= now
        if revoked:
            revoked_count += 1
        elif not expired:
            live_count += 1
        listed.append(
            {
                "id": row["id"],
                "sid": _mask(row["sid"]),
                "scope": row["scope"],
                "guild_id": str(row["guild_id"]) if row["guild_id"] else "",
                "user_id": str(row["user_id"]) if row["user_id"] else "",
                "label": row["label"],
                "ip": row["ip"],
                "agent": row["agent"],
                "started_at": row["started_at"],
                "seen_at": row["seen_at"],
                "expires_at": row["expires_at"],
                "revoked_at": row["revoked_at"],
                "state": (
                    "revoked" if revoked else "expired" if expired else "live"
                ),
                "current": bool(current_sid) and row["sid"] == current_sid,
            }
        )
    return {
        "available": True,
        "because": "",
        "idle_ttl_seconds": IDLE_TTL_SECONDS,
        "rows": listed,
        "live": live_count,
        "revoked": revoked_count,
    }


def writable() -> bool:
    """Whether a sign-in can be recorded here at all, for the reading's honesty."""
    return _writes_allowed()
